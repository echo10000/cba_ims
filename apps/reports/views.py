class EmployeeAccountabilityReportView(NonFacultyRequiredMixin, View):
    """Individual Employee Accountability Profile Report."""
    def get(self, request, pk):
        user = request.user
        chair_dept = services.get_user_department_scope(user)

        employee = get_object_or_404(Employee.objects.select_related('department', 'location'), pk=pk)

        # Scoping check
        if chair_dept and employee.department != chair_dept:
            raise PermissionDenied("You cannot view accountability for an employee outside your department.")

        active_assignments = employee.assignments.filter(
            status=AssetAssignment.Status.ACTIVE
        ).select_related('asset', 'asset__category', 'asset__current_location', 'assigned_by')

        past_assignments = employee.assignments.filter(
            status=AssetAssignment.Status.RETURNED
        ).select_related('asset', 'asset__category', 'assigned_by', 'returned_by')

        export_format = request.GET.get('export', '').lower()
        if export_format in ['csv', 'xlsx']:
            meta = {
                'Employee': employee.full_name,
                'Employee ID': employee.employee_id,
                'Department': employee.department.name if employee.department else "—",
                'Position': employee.position or "Staff",
                'Active Assignments Count': active_assignments.count(),
                'Generated At': timezone.now().strftime('%Y-%m-%d %H:%M:%S'),
                'Generated By': user.get_full_name() or user.username,
            }
            headers, rows, col_types = services.format_accountability_rows(active_assignments, historical=False)
            filename = f"CBA_Accountability_{employee.employee_id}_{timezone.now():%Y%m%d}"
            if export_format == 'csv':
                return exporters.export_to_csv(f"{filename}.csv", f"Accountability: {employee.full_name}", meta, headers, rows)
            else:
                return exporters.export_to_xlsx(f"{filename}.xlsx", f"Accountability: {employee.full_name}", meta, headers, rows, sheet_name="Accountability", column_types=col_types)

        if request.GET.get('print') == '1':
            return render(request, 'reports/report_print.html', {
                'report_title': f"Employee Accountability: {employee.full_name} ({employee.employee_id})",
                'metadata': {
                    'Department': employee.department.name if employee.department else "—",
                    'Position': employee.position or "Staff",
                    'Active Custody Items': active_assignments.count(),
                },
                'items': active_assignments,
                'headers': ["Asset Code", "Property #", "Item", "Category", "Location", "Condition", "Assigned Date", "Purpose"],
                'report_type': 'employee_accountability',
            })

        return render(request, 'reports/employee_accountability_report.html', {
            'employee': employee,
            'active_assignments': active_assignments,
            'past_assignments': past_assignments,
            'page_title': f"Accountability: {employee.full_name}",
        })


