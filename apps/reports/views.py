class AssetInventoryReportView(NonFacultyRequiredMixin, View):
    """
    Comprehensive Asset Inventory Report.
    Supports on-screen pagination, CSV export, openpyxl XLSX export, and print view.
    """
    def get(self, request):
        user = request.user
        filters = request.GET.dict()
        assets_qs, summary = services.get_asset_inventory_report(user, filters)

        export_format = request.GET.get('export', '').lower()
        is_print = request.GET.get('print') == '1'

        filter_labels = {
            'scope': 'Scope', 'department': 'Department ID', 'location': 'Location ID',
            'category': 'Category ID', 'brand': 'Brand ID', 'condition': 'Condition',
            'status': 'Status', 'date_from': 'Acquired From', 'date_to': 'Acquired To', 'q': 'Search'
        }
        meta = build_active_filters_meta(request, filter_labels)

        # 1. CSV Export
        if export_format == 'csv':
            headers, rows, _ = services.format_asset_inventory_rows(assets_qs)
            filename = f"CBA_Asset_Inventory_{timezone.now():%Y%m%d}.csv"
            return exporters.export_to_csv(filename, "Asset Inventory Report", meta, headers, rows)

        # 2. XLSX Export
        if export_format == 'xlsx':
            headers, rows, col_types = services.format_asset_inventory_rows(assets_qs)
            filename = f"CBA_Asset_Inventory_{timezone.now():%Y%m%d}.xlsx"
            return exporters.export_to_xlsx(filename, "Asset Inventory Report", meta, headers, rows, sheet_name="Inventory", column_types=col_types)

        # 3. Print View
        if is_print:
            return render(request, 'reports/report_print.html', {
                'report_title': "Asset Inventory Report",
                'metadata': meta,
                'summary': summary,
                'items': assets_qs[:500],
                'headers': ["Code", "Property #", "Item", "Category", "Department", "Location", "Condition", "Status", "Acquired", "Cost (₱)"],
                'report_type': 'assets',
            })

        # 4. Standard On-Screen View (Paginated)
        paginator = Paginator(assets_qs, 25)
        page_number = request.GET.get('page')
        page_obj = paginator.get_page(page_number)

        # Filter dropdown choices
        chair_dept = services.get_user_department_scope(user)
        departments = Department.objects.filter(pk=chair_dept.pk) if chair_dept else Department.objects.filter(is_active=True)
        locations = Location.objects.filter(department=chair_dept, is_active=True) if chair_dept else Location.objects.filter(is_active=True)

        query_params = request.GET.copy()
        if 'page' in query_params:
            query_params.pop('page')

        return render(request, 'reports/asset_inventory_report.html', {
            'page_title': "Asset Inventory Report",
            'assets': page_obj,
            'page_obj': page_obj,
            'summary': summary,
            'departments': departments,
            'locations': locations,
            'categories': AssetCategory.objects.filter(is_active=True),
            'brands': Brand.objects.filter(is_active=True),
            'conditions': Asset.Condition.choices,
            'statuses': Asset.Status.choices,
            'query_string': query_params.urlencode(),
            'active_filters': filters,
            'chair_dept': chair_dept,
        })


