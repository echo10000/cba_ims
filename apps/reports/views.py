class ReportsDashboardView(NonFacultyRequiredMixin, TemplateView):
    """
    Central catalog of all available operational, accountability,
    inventory, and supply reports.
    """
    template_name = 'reports/reports_dashboard.html'

    def get_context_data(self, **kwargs):
        context = super().get_context_data(**kwargs)
        user = self.request.user
        chair_dept = services.get_user_department_scope(user)

        # Quick summary metrics for dashboard cards
        asset_qs = Asset.objects.all()
        if chair_dept:
            asset_qs = asset_qs.filter(department=chair_dept)

        context['total_assets'] = asset_qs.count()
        context['active_assets'] = asset_qs.exclude(status=Asset.Status.DISPOSED).count()
        context['disposed_assets'] = asset_qs.filter(status=Asset.Status.DISPOSED).count()

        # Accountability
        assign_qs = AssetAssignment.objects.filter(status=AssetAssignment.Status.ACTIVE)
        if chair_dept:
            assign_qs = assign_qs.filter(Q(employee__department=chair_dept) | Q(asset__department=chair_dept))
        context['active_assignments'] = assign_qs.count()

        # Transfers
        trans_qs = AssetTransfer.objects.all()
        if chair_dept:
            trans_qs = trans_qs.filter(Q(from_department=chair_dept) | Q(to_department=chair_dept))
        context['total_transfers'] = trans_qs.count()

        # Borrowing
        brw_qs = AssetBorrowing.objects.all()
        if chair_dept:
            brw_qs = brw_qs.filter(Q(borrower__department=chair_dept) | Q(asset__department=chair_dept))
        context['active_loans'] = brw_qs.filter(status__in=[AssetBorrowing.Status.RELEASED, AssetBorrowing.Status.OVERDUE]).count()

        # Maintenance
        mnt_qs = AssetMaintenance.objects.all()
        if chair_dept:
            mnt_qs = mnt_qs.filter(asset__department=chair_dept)
        context['open_maintenance'] = mnt_qs.filter(status__in=[
            AssetMaintenance.Status.REPORTED, AssetMaintenance.Status.ASSESSED, AssetMaintenance.Status.IN_REPAIR
        ]).count()

        # Supplies
        context['low_stock_count'] = len(services.supply_services.get_low_stock_supplies())

        # Disposals
        dsp_qs = AssetDisposal.objects.all()
        if chair_dept:
            dsp_qs = dsp_qs.filter(asset__department=chair_dept)
        context['completed_disposals'] = dsp_qs.filter(status=AssetDisposal.Status.COMPLETED).count()

        context['page_title'] = "Operational Reports Catalog"
        context['is_admin'] = getattr(user, 'is_admin', False)
        context['chair_dept'] = chair_dept
        return context


