class NonFacultyRequiredMixin(LoginRequiredMixin, UserPassesTestMixin):
    """
    Restricts reporting access to Admin, Dean, and Department Chair.
    Faculty members have personal accountability portals and cannot access
    administrative reports.
    """
    def test_func(self):
        user = self.request.user
        if not user.is_authenticated:
            return False
        return getattr(user, 'is_admin', False) or getattr(user, 'role', '') in [
            User.Role.ADMIN, User.Role.DEAN, User.Role.DEPT_CHAIR
        ]

    def handle_no_permission(self):
        if self.request.user.is_authenticated and getattr(self.request.user, 'role', '') == User.Role.FACULTY:
            raise PermissionDenied("Faculty members do not have access to administrative reporting.")
        return super().handle_no_permission()


class AdminOnlyRequiredMixin(LoginRequiredMixin, UserPassesTestMixin):
    """Restricts view exclusively to System Administrators."""
    def test_func(self):
        user = self.request.user
        return user.is_authenticated and getattr(user, 'is_admin', False)

    def handle_no_permission(self):
        raise PermissionDenied("Only System Administrators can access this report.")


def build_active_filters_meta(request, filter_labels):
    """Builds a human-readable dict of active filters for exports and headers."""
    meta = {
        'Generated At': timezone.now().strftime('%Y-%m-%d %H:%M:%S'),
        'Generated By': request.user.get_full_name() or request.user.username,
    }
    active_filters_list = []
    for param, label in filter_labels.items():
        val = request.GET.get(param, '').strip()
        if val:
            active_filters_list.append(f"{label}: {val}")
    
    meta['Active Filters'] = "; ".join(active_filters_list) if active_filters_list else "None (All Records)"
    return meta


